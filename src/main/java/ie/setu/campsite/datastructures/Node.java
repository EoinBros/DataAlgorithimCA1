package ie.setu.campsite.datastructures;

import java.io.Serializable;

// a single node in the linked list - holds the data and points to the next one
public class Node<T> implements Serializable {
    private T data;
    private Node<T> next;

    public Node(T data) {
        this.data = data;
        this.next = null;
    }

    public T getData() {
        return data;
    }

    public void setData(T data) {
        this.data = data;
    }

    public Node<T> getNext() {
        return next;
    }

    public void setNext(Node<T> next) {
        this.next = next;
    }
}
